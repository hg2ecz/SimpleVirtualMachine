    ; (cx+x, cy-y)
    GFX_X0 LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00B8 STORE16
    GFX_TMP0 LOAD16 0x00B0 STORE16
    0x00B8 LOAD16 0x00B0 LOAD16 ADD 0x00B8 STORE16
    GFX_Y0 LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00BA STORE16
    GFX_I LOAD16 0x00B0 STORE16
    0x00BA LOAD16 0x00B0 LOAD16 SUB 0x00BA STORE16
    0x00B8 LOAD16 0x00B0 STORE16
    0x00BA LOAD16 0x00B2 STORE16
    0x00B0 LOAD16 0x00B2 LOAD16 CALL putpixel
    RET
.endproc

; circle: GFX_X0=cx, GFX_Y0=cy, GFX_R=r, GFX_COLOR=color.
; Uses an integer scan of the first octant; circle must fit on screen.
.proc circle
    GFX_COLOR LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 CALL gfx_set_color
    GFX_R LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 GFX_TMP0 STORE16
    0x00B0 LOAD16 0x00B8 STORE16
    0x00B8 LOAD16 0x00B8 LOAD16 MUL 0x00B8 STORE16
    0x00B8 LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 GFX_TMP1 STORE16
    0 0x00B0 STORE16
    0x00B0 LOAD16 GFX_I STORE16
circle_y_loop:
circle_find_x:
    GFX_TMP0 LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00B8 STORE16
    0x00B8 LOAD16 0x00B8 LOAD16 MUL 0x00B8 STORE16
    GFX_I LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00BA STORE16
    0x00BA LOAD16 0x00BA LOAD16 MUL 0x00BA STORE16
    0x00B8 LOAD16 0x00BA LOAD16 ADD 0x00B8 STORE16
    GFX_TMP1 LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00BA STORE16
    0x00B8 LOAD16 0x00BA LOAD16 ULT JNZ circle_x_ready
    0x00B8 LOAD16 0x00BA LOAD16 EQ JNZ circle_x_ready
    GFX_TMP0 LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 1 SUB 0x00B0 STORE16
    0x00B0 LOAD16 GFX_TMP0 STORE16
    JMP circle_find_x
circle_x_ready:
    CALL __gfx_circle_points
    GFX_I LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00B8 STORE16
    GFX_R LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00BA STORE16
    0x00B8 LOAD16 0x00BA LOAD16 EQ JNZ circle_done
    GFX_I LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 1 ADD 0x00B0 STORE16
    0x00B0 LOAD16 GFX_I STORE16
    JMP circle_y_loop
circle_done:
    RET
.endproc

; fillcircle: same parameters as circle. Circle must fit on screen.
.proc fillcircle
