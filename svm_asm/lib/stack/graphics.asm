\ Stack ISA 320x200x2-bpp graphics helpers.
\ Scratch: 0x00E8 color, 0x00EA..0x00F6 temporaries.
\ ABI: gfx_set_color ( color -- ); gfx_set_palette ( p0 p1 p2 p3 -- );
\ putpixel ( x y -- ); clear ( color -- ); hline ( x0 x1 y -- ); vline ( x y0 y1 -- ).
.proc gfx_set_color
    3 AND 0x00E8 STORE8
    RET
.endproc

.proc gfx_set_palette
    0x00EE STORE16
    0x00EC STORE16
    0x00EA STORE16
    0x00E8 STORE16
    0x00E8 LOAD16 0xFF0C STORE8
    0x00EA LOAD16 0xFF0D STORE8
    0x00EC LOAD16 0xFF0E STORE8
    0x00EE LOAD16 0xFF0F STORE8
    RET
.endproc

.proc putpixel
    0x00EC STORE16
    0x00EA STORE16
    0x00EC LOAD16 80 MUL
    0x00EA LOAD16 2 SHR ADD
    0x00F0 STORE16
    6 0x00EA LOAD16 3 AND SHL1 SUB
    0x00F2 STORE16
    0x00F0 LOAD16 VLOAD8
    3 0x00F2 LOAD16 SHL NOT AND
    0x00E8 LOAD8 0x00F2 LOAD16 SHL OR
    0x00F0 LOAD16 VSTORE8
    RET
.endproc

.proc clear
    3 AND 0x55 MUL 0x00EA STORE16
    0 0x00EC STORE16
    16000 0x00EE STORE16
clear_loop:
    0x00EA LOAD16 0x00EC LOAD16 VSTORE8
    0x00EC LOAD16 1 ADD 0x00EC STORE16
    0x00EE LOAD16 1 SUB DUP 0x00EE STORE16
    JNZ clear_loop
    RET
.endproc

.proc hline
    0x00EE STORE16
    0x00EC STORE16
    0x00EA STORE16
hline_loop:
    0x00EA LOAD16 0x00EE LOAD16 CALL putpixel
    0x00EA LOAD16 0x00EC LOAD16 EQ IF RET THEN
    0x00EA LOAD16 1 ADD 0x00EA STORE16
    JMP hline_loop
.endproc

.proc vline
    0x00EE STORE16
    0x00EC STORE16
    0x00EA STORE16
vline_loop:
    0x00EA LOAD16 0x00EC LOAD16 CALL putpixel
    0x00EC LOAD16 0x00EE LOAD16 EQ IF RET THEN
    0x00EC LOAD16 1 ADD 0x00EC STORE16
    JMP vline_loop
.endproc

; ---- High-level geometry -------------------------------------------------
; Shared parameter block for calls that do not fit naturally in registers.
; Including graphics.asm reserves 0x00B0..0x00FA for graphics parameters,
; current colour and internal scratch.
.equ GFX_X0,     0x00C0
.equ GFX_Y0,     0x00C2
.equ GFX_X1,     0x00C4
.equ GFX_Y1,     0x00C6
.equ GFX_W,      0x00C8
.equ GFX_H,      0x00CA
.equ GFX_R,      0x00CC
.equ GFX_COLOR,  0x00CE
.equ GFX_I,      0x00D0
.equ GFX_DX,     0x00D2
.equ GFX_DY,     0x00D4
.equ GFX_SX,     0x00D6
.equ GFX_SY,     0x00D8
.equ GFX_TMP0,   0x00DA
.equ GFX_TMP1,   0x00DC
.equ GFX_TMP2,   0x00DE
.equ GFX_TMP3,   0x00E0
.equ GFX_TMP4,   0x00E2
.equ GFX_TMP5,   0x00E4
.equ GFX_TMP6,   0x00E6

; line: integer DDA, screen-coordinate domain. Parameters:
; GFX_X0=x0, GFX_Y0=y0, GFX_X1=x1, GFX_Y1=y1, GFX_COLOR=color.
; Products are bounded by 319*199 and fit in 16 bits for in-screen points.
.proc line
    GFX_COLOR LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 CALL gfx_set_color

    GFX_X0 LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00B8 STORE16
    GFX_X1 LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00BA STORE16
    0x00BA LOAD16 0x00B8 LOAD16 ULT JNZ line_x_negative
    0x00BA LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00B8 LOAD16 SUB 0x00B0 STORE16
    0x00B0 LOAD16 GFX_DX STORE16
    1 0x00B0 STORE16
    0x00B0 LOAD16 GFX_SX STORE16
    JMP line_x_ready
line_x_negative:
    0x00B8 LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00BA LOAD16 SUB 0x00B0 STORE16
    0x00B0 LOAD16 GFX_DX STORE16
    0 0x00B0 STORE16
    0x00B0 LOAD16 GFX_SX STORE16
line_x_ready:
    GFX_Y0 LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00B8 STORE16
    GFX_Y1 LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00BA STORE16
    0x00BA LOAD16 0x00B8 LOAD16 ULT JNZ line_y_negative
    0x00BA LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00B8 LOAD16 SUB 0x00B0 STORE16
    0x00B0 LOAD16 GFX_DY STORE16
    1 0x00B0 STORE16
    0x00B0 LOAD16 GFX_SY STORE16
    JMP line_y_ready
line_y_negative:
    0x00B8 LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00BA LOAD16 SUB 0x00B0 STORE16
    0x00B0 LOAD16 GFX_DY STORE16
    0 0x00B0 STORE16
    0x00B0 LOAD16 GFX_SY STORE16
line_y_ready:
    GFX_X0 LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 GFX_TMP0 STORE16
    GFX_Y0 LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 GFX_TMP1 STORE16
    0 0x00B0 STORE16
    0x00B0 LOAD16 GFX_I STORE16

    GFX_DX LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00B8 STORE16
    GFX_DY LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00BA STORE16
    0x00B8 LOAD16 0x00BA LOAD16 ULT JNZ line_vertical_major

line_horizontal_loop:
    ; y = y0 +/- (i*dy/dx), x is maintained in TMP0.
    GFX_I LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00BA STORE16
    GFX_DY LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00BC STORE16
    0x00BA LOAD16 0x00BC LOAD16 MUL 0x00BA STORE16
    ; dx is non-zero here unless this is a single pixel.
    ; Handle dx=0 explicitly to avoid a DIV-by-zero trap.
    GFX_DX LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00BC STORE16
    0 0x00BE STORE16
    0x00BC LOAD16 0x00BE LOAD16 EQ JNZ line_single_pixel
    0x00BA LOAD16 0x00BC LOAD16 DIV 0x00BA STORE16
    GFX_Y0 LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00B2 STORE16
    GFX_SY LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00BC STORE16
    0 0x00BE STORE16
    0x00BC LOAD16 0x00BE LOAD16 EQ JNZ line_h_sub_y
    0x00B2 LOAD16 0x00BA LOAD16 ADD 0x00B2 STORE16
    JMP line_h_y_ready
line_h_sub_y:
    0x00B2 LOAD16 0x00BA LOAD16 SUB 0x00B2 STORE16
line_h_y_ready:
    GFX_TMP0 LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00B2 LOAD16 CALL putpixel

    GFX_I LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00B8 STORE16
    GFX_DX LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00BA STORE16
    0x00B8 LOAD16 0x00BA LOAD16 EQ JNZ line_done
    GFX_SX LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00BC STORE16
    0 0x00BE STORE16
    GFX_TMP0 LOAD16 0x00B0 STORE16
    0x00BC LOAD16 0x00BE LOAD16 EQ JNZ line_h_dec_x
    0x00B0 LOAD16 1 ADD 0x00B0 STORE16
    JMP line_h_store_x
line_h_dec_x:
    0x00B0 LOAD16 1 SUB 0x00B0 STORE16
line_h_store_x:
    0x00B0 LOAD16 GFX_TMP0 STORE16
    GFX_I LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 1 ADD 0x00B0 STORE16
    0x00B0 LOAD16 GFX_I STORE16
    JMP line_horizontal_loop

line_vertical_major:
    GFX_DY LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00BC STORE16
    0 0x00BE STORE16
    0x00BC LOAD16 0x00BE LOAD16 EQ JNZ line_single_pixel
line_vertical_loop:
    ; x = x0 +/- (i*dx/dy), y is maintained in TMP1.
    GFX_I LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00BA STORE16
    GFX_DX LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00BC STORE16
    0x00BA LOAD16 0x00BC LOAD16 MUL 0x00BA STORE16
    GFX_DY LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00BC STORE16
    0x00BA LOAD16 0x00BC LOAD16 DIV 0x00BA STORE16
    GFX_X0 LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00B8 STORE16
    GFX_SX LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00BC STORE16
    0 0x00BE STORE16
    0x00BC LOAD16 0x00BE LOAD16 EQ JNZ line_v_sub_x
    0x00B8 LOAD16 0x00BA LOAD16 ADD 0x00B8 STORE16
    JMP line_v_x_ready
line_v_sub_x:
    0x00B8 LOAD16 0x00BA LOAD16 SUB 0x00B8 STORE16
line_v_x_ready:
    0x00B8 LOAD16 0x00B0 STORE16
    GFX_TMP1 LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00B2 STORE16
    0x00B8 LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00B2 LOAD16 CALL putpixel

    GFX_I LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00B8 STORE16
    GFX_DY LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00BA STORE16
    0x00B8 LOAD16 0x00BA LOAD16 EQ JNZ line_done
    GFX_SY LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00BC STORE16
    0 0x00BE STORE16
    GFX_TMP1 LOAD16 0x00B0 STORE16
    0x00BC LOAD16 0x00BE LOAD16 EQ JNZ line_v_dec_y
    0x00B0 LOAD16 1 ADD 0x00B0 STORE16
    JMP line_v_store_y
line_v_dec_y:
    0x00B0 LOAD16 1 SUB 0x00B0 STORE16
line_v_store_y:
    0x00B0 LOAD16 GFX_TMP1 STORE16
    GFX_I LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 1 ADD 0x00B0 STORE16
    0x00B0 LOAD16 GFX_I STORE16
    JMP line_vertical_loop

line_single_pixel:
    GFX_X0 LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00B8 STORE16
    GFX_Y0 LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00B2 STORE16
    0x00B8 LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00B2 LOAD16 CALL putpixel
line_done:
    RET
.endproc

