    0x00BC LOAD16 0x00B4 STORE16
    0x00B0 LOAD16 0x00B2 LOAD16 0x00B4 LOAD16 CALL hline
    ; span at cy-y, skip duplicate y=0
    GFX_I LOAD16 0x00B0 STORE16
    0x00B0 LOAD16 0x00B8 STORE16
