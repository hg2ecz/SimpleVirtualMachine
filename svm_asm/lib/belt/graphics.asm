; circle: GFX_X0=cx, GFX_Y0=cy, GFX_R=r, GFX_COLOR=color.
; Uses an integer scan of the first octant; circle must fit on screen.
.proc circle
    ZLD16 GFX_COLOR
    ZST16 0xB0,b0
    ZLD16 0xB0
    CALL gfx_set_color
    ZLD16 GFX_R
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 GFX_TMP0,b0
    ZLD16 0xB0
    ZST16 0xB8,b0
    ZLD16 0xB8
    ZLD16 0xB8
    MUL b1,b0
    ZST16 0xB8,b0
    ZLD16 0xB8
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 GFX_TMP1,b0
    LDI 0
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 GFX_I,b0
circle_y_loop:
circle_find_x:
    ZLD16 GFX_TMP0
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xB8,b0
    ZLD16 0xB8
    ZLD16 0xB8
    MUL b1,b0
    ZST16 0xB8,b0
    ZLD16 GFX_I
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xBA,b0
    ZLD16 0xBA
    ZLD16 0xBA
    MUL b1,b0
    ZST16 0xBA,b0
    ZLD16 0xB8
    ZLD16 0xBA
    ADD b1,b0
    ZST16 0xB8,b0
    ZLD16 GFX_TMP1
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xBA,b0
    ZLD16 0xB8
    ZLD16 0xBA
    CMP b1,b0
    JNC circle_x_ready
    JZ circle_x_ready
    ZLD16 GFX_TMP0
    ZST16 0xB0,b0
    ZLD16 0xB0
    LDI 1
    SUB b1,b0
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 GFX_TMP0,b0
    JMP circle_find_x
circle_x_ready:
    CALL __gfx_circle_points
    ZLD16 GFX_I
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xB8,b0
    ZLD16 GFX_R
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xBA,b0
    ZLD16 0xB8
    ZLD16 0xBA
    CMP b1,b0
    JZ circle_done
    ZLD16 GFX_I
    ZST16 0xB0,b0
    ZLD16 0xB0
    LDI 1
    ADD b1,b0
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 GFX_I,b0
    JMP circle_y_loop
circle_done:
    RET
.endproc

