; Belt16 320x200x2-bpp graphics helpers.
; Zero-page scratch 0xE8..0xF8. ABI: gfx_set_color b0=color;
; gfx_set_palette b0=p0,b1=p1,b2=p2,b3=p3; putpixel b0=x,b1=y;
; clear b0=color; hline b0=x0,b1=x1,b2=y; vline b0=x,b1=y0,b2=y1.
.proc gfx_set_color
    LDI 3
    AND b1,b0
    ZST8 0xE8,b0
    RET
.endproc

.proc gfx_set_palette
    ST8A 0xFF0C,b0
    ST8A 0xFF0D,b1
    ST8A 0xFF0E,b2
    ST8A 0xFF0F,b3
    RET
.endproc

.proc putpixel
    ZST16 0xEA,b0
    ZST16 0xEC,b1
    ZLD16 0xEC
    LDI 80
    MUL b1,b0
    ZST16 0xEE,b0
    ZLD16 0xEA
    LDI 2
    SHR b1,b0
    ZLD16 0xEE
    ADD b0,b1
    ZST16 0xF0,b0
    VLD8 [b0]
    ZST16 0xF2,b0
    ZLD16 0xEA
    LDI 3
    AND b1,b0
    SHL1 b0
    LDI 6
    SUB b0,b1
    ZST16 0xF4,b0
    LDI 3
    ZLD16 0xF4
    SHL b1,b0
    NOT b0
    ZLD16 0xF2
    AND b0,b1
    ZST16 0xF6,b0
    ZLD8 0xE8
    ZLD16 0xF4
    SHL b1,b0
    ZLD16 0xF6
    OR b0,b1
    ZLD16 0xF0
    VST8 [b0],b1
    RET
.endproc

.proc clear
    LDI 3
    AND b1,b0
    LDI 0x55
    MUL b1,b0
    ZST16 0xEA,b0
    LDI 0
    ZST16 0xEC,b0
    LDI 16000
    ZST16 0xEE,b0
clear_loop:
    ZLD16 0xEC
    ZLD16 0xEA
    VST8 [b1],b0
    ZLD16 0xEC
    LDI 1
    ADD b1,b0
    ZST16 0xEC,b0
    ZLD16 0xEE
    LDI 1
    SUB b1,b0
    ZST16 0xEE,b0
    JNZ clear_loop
    RET
.endproc

.proc hline
    ZST16 0xEA,b0
    ZST16 0xEC,b1
    ZST16 0xEE,b2
hline_loop:
    ZLD16 0xEE
    ZLD16 0xEA
    CALL putpixel
    ZLD16 0xEA
    ZLD16 0xEC
    CMP b1,b0
    JZ hline_done
    ZLD16 0xEA
    LDI 1
    ADD b1,b0
    ZST16 0xEA,b0
    JMP hline_loop
hline_done:
    RET
.endproc

.proc vline
    ZST16 0xEA,b0
    ZST16 0xEC,b1
    ZST16 0xEE,b2
vline_loop:
    ZLD16 0xEC
    ZLD16 0xEA
    CALL putpixel
    ZLD16 0xEC
    ZLD16 0xEE
    CMP b1,b0
    JZ vline_done
    ZLD16 0xEC
    LDI 1
    ADD b1,b0
    ZST16 0xEC,b0
    JMP vline_loop
vline_done:
    RET
.endproc

; ---- High-level geometry -------------------------------------------------
; Shared parameter block for calls that do not fit naturally in registers.
; Including graphics.asm reserves 0x00B0..0x00FA for graphics parameters,
; current colour and internal scratch.
.equ GFX_X0,     0x00C0
.equ GFX_Y0,     0x00C2
.equ GFX_X1,     0x00C4
.equ GFX_Y1,     0x00C6
.equ GFX_W,      0x00C8
.equ GFX_H,      0x00CA
.equ GFX_R,      0x00CC
.equ GFX_COLOR,  0x00CE
.equ GFX_I,      0x00D0
.equ GFX_DX,     0x00D2
.equ GFX_DY,     0x00D4
.equ GFX_SX,     0x00D6
.equ GFX_SY,     0x00D8
.equ GFX_TMP0,   0x00DA
.equ GFX_TMP1,   0x00DC
.equ GFX_TMP2,   0x00DE
.equ GFX_TMP3,   0x00E0
.equ GFX_TMP4,   0x00E2
.equ GFX_TMP5,   0x00E4
.equ GFX_TMP6,   0x00E6

; line: integer DDA, screen-coordinate domain. Parameters:
; GFX_X0=x0, GFX_Y0=y0, GFX_X1=x1, GFX_Y1=y1, GFX_COLOR=color.
; Products are bounded by 319*199 and fit in 16 bits for in-screen points.
.proc line
    ZLD16 GFX_COLOR
    ZST16 0xB0,b0
    ZLD16 0xB0
    CALL gfx_set_color

    ZLD16 GFX_X0
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xB8,b0
    ZLD16 GFX_X1
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xBA,b0
    ZLD16 0xBA
    ZLD16 0xB8
    CMP b1,b0
    JNC line_x_negative
    ZLD16 0xBA
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZLD16 0xB8
    SUB b1,b0
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 GFX_DX,b0
    LDI 1
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 GFX_SX,b0
    JMP line_x_ready
line_x_negative:
    ZLD16 0xB8
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZLD16 0xBA
    SUB b1,b0
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 GFX_DX,b0
    LDI 0
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 GFX_SX,b0
line_x_ready:
    ZLD16 GFX_Y0
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xB8,b0
    ZLD16 GFX_Y1
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xBA,b0
    ZLD16 0xBA
    ZLD16 0xB8
    CMP b1,b0
    JNC line_y_negative
    ZLD16 0xBA
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZLD16 0xB8
    SUB b1,b0
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 GFX_DY,b0
    LDI 1
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 GFX_SY,b0
    JMP line_y_ready
line_y_negative:
    ZLD16 0xB8
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZLD16 0xBA
    SUB b1,b0
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 GFX_DY,b0
    LDI 0
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 GFX_SY,b0
line_y_ready:
    ZLD16 GFX_X0
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 GFX_TMP0,b0
    ZLD16 GFX_Y0
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 GFX_TMP1,b0
    LDI 0
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 GFX_I,b0

    ZLD16 GFX_DX
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xB8,b0
    ZLD16 GFX_DY
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xBA,b0
    ZLD16 0xB8
    ZLD16 0xBA
    CMP b1,b0
    JNC line_vertical_major

line_horizontal_loop:
    ; y = y0 +/- (i*dy/dx), x is maintained in TMP0.
    ZLD16 GFX_I
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xBA,b0
    ZLD16 GFX_DY
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xBC,b0
    ZLD16 0xBA
    ZLD16 0xBC
    MUL b1,b0
    ZST16 0xBA,b0
    ; dx is non-zero here unless this is a single pixel.
    ; Handle dx=0 explicitly to avoid a DIV-by-zero trap.
    ZLD16 GFX_DX
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xBC,b0
    LDI 0
    ZST16 0xBE,b0
    ZLD16 0xBC
    ZLD16 0xBE
    CMP b1,b0
    JZ line_single_pixel
    ZLD16 0xBA
    ZLD16 0xBC
    DIV b1,b0
    ZST16 0xBA,b0
    ZLD16 GFX_Y0
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xB2,b0
    ZLD16 GFX_SY
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xBC,b0
    LDI 0
    ZST16 0xBE,b0
    ZLD16 0xBC
    ZLD16 0xBE
    CMP b1,b0
    JZ line_h_sub_y
    ZLD16 0xB2
    ZLD16 0xBA
    ADD b1,b0
    ZST16 0xB2,b0
    JMP line_h_y_ready
line_h_sub_y:
    ZLD16 0xB2
    ZLD16 0xBA
    SUB b1,b0
    ZST16 0xB2,b0
line_h_y_ready:
    ZLD16 GFX_TMP0
    ZST16 0xB0,b0
    ZLD16 0xB2
    ZLD16 0xB0
    CALL putpixel

    ZLD16 GFX_I
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xB8,b0
    ZLD16 GFX_DX
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xBA,b0
    ZLD16 0xB8
    ZLD16 0xBA
    CMP b1,b0
    JZ line_done
    ZLD16 GFX_SX
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xBC,b0
    LDI 0
    ZST16 0xBE,b0
    ZLD16 0xBC
    ZLD16 0xBE
    CMP b1,b0
    ZLD16 GFX_TMP0
    ZST16 0xB0,b0
    JZ line_h_dec_x
    ZLD16 0xB0
    LDI 1
    ADD b1,b0
    ZST16 0xB0,b0
    JMP line_h_store_x
line_h_dec_x:
    ZLD16 0xB0
    LDI 1
    SUB b1,b0
    ZST16 0xB0,b0
line_h_store_x:
    ZLD16 0xB0
    ZST16 GFX_TMP0,b0
    ZLD16 GFX_I
    ZST16 0xB0,b0
    ZLD16 0xB0
    LDI 1
    ADD b1,b0
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 GFX_I,b0
    JMP line_horizontal_loop

line_vertical_major:
    ZLD16 GFX_DY
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xBC,b0
    LDI 0
    ZST16 0xBE,b0
    ZLD16 0xBC
    ZLD16 0xBE
    CMP b1,b0
    JZ line_single_pixel
line_vertical_loop:
    ; x = x0 +/- (i*dx/dy), y is maintained in TMP1.
    ZLD16 GFX_I
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xBA,b0
    ZLD16 GFX_DX
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xBC,b0
    ZLD16 0xBA
    ZLD16 0xBC
    MUL b1,b0
    ZST16 0xBA,b0
    ZLD16 GFX_DY
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xBC,b0
    ZLD16 0xBA
    ZLD16 0xBC
    DIV b1,b0
    ZST16 0xBA,b0
    ZLD16 GFX_X0
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xB8,b0
    ZLD16 GFX_SX
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xBC,b0
    LDI 0
    ZST16 0xBE,b0
    ZLD16 0xBC
    ZLD16 0xBE
    CMP b1,b0
    JZ line_v_sub_x
    ZLD16 0xB8
    ZLD16 0xBA
    ADD b1,b0
    ZST16 0xB8,b0
    JMP line_v_x_ready
line_v_sub_x:
    ZLD16 0xB8
    ZLD16 0xBA
    SUB b1,b0
    ZST16 0xB8,b0
line_v_x_ready:
    ZLD16 0xB8
    ZST16 0xB0,b0
    ZLD16 GFX_TMP1
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xB2,b0
    ZLD16 0xB8
    ZST16 0xB0,b0
    ZLD16 0xB2
    ZLD16 0xB0
    CALL putpixel

    ZLD16 GFX_I
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xB8,b0
    ZLD16 GFX_DY
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xBA,b0
    ZLD16 0xB8
    ZLD16 0xBA
    CMP b1,b0
    JZ line_done
    ZLD16 GFX_SY
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xBC,b0
    LDI 0
    ZST16 0xBE,b0
    ZLD16 0xBC
    ZLD16 0xBE
    CMP b1,b0
    ZLD16 GFX_TMP1
    ZST16 0xB0,b0
    JZ line_v_dec_y
    ZLD16 0xB0
    LDI 1
    ADD b1,b0
    ZST16 0xB0,b0
    JMP line_v_store_y
line_v_dec_y:
    ZLD16 0xB0
    LDI 1
    SUB b1,b0
    ZST16 0xB0,b0
line_v_store_y:
    ZLD16 0xB0
    ZST16 GFX_TMP1,b0
    ZLD16 GFX_I
    ZST16 0xB0,b0
    ZLD16 0xB0
    LDI 1
    ADD b1,b0
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 GFX_I,b0
    JMP line_vertical_loop

line_single_pixel:
    ZLD16 GFX_X0
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xB8,b0
    ZLD16 GFX_Y0
    ZST16 0xB0,b0
    ZLD16 0xB0
    ZST16 0xB2,b0
    ZLD16 0xB8
    ZST16 0xB0,b0
    ZLD16 0xB2
    ZLD16 0xB0
    CALL putpixel
line_done:
    RET
.endproc

