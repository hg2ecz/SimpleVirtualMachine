#[derive(Default)]
pub struct Video;
impl Video {
    pub fn framebuffer<'a>(&self, m: &'a Memory) -> &'a [u8] {
        m.framebuffer()
    }
    pub fn to_argb8888(&self, m: &Memory, out: &mut [u32]) -> Result<(), VmError> {
        let expected = WIDTH * HEIGHT;
        if out.len() != expected {
            return Err(VmError::InvalidVideoBufferSize {
                expected,
                actual: out.len(),
            });
        }
        let palette = m.palette();
        let fb = m.framebuffer();
        for (i, d) in out.iter_mut().enumerate() {
            let packed = fb[i / 4];
            let shift = 6 - ((i & 3) * 2);
            let slot = ((packed >> shift) & 0x03) as usize;
            let master = (palette[slot] & 0x0F) as usize;
            *d = 0xFF00_0000 | MASTER_PALETTE[master];
        }
        Ok(())
    }
}

